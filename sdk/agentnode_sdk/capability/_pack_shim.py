"""The generated stdio MCP shim for an imported AgentNode registry pack (product code).

``pack_import`` renders exactly one shim per pack from ONE versioned template and ONE canonical
JSON tool table. Nothing else varies: no timestamp, no path, no randomness, no interpreter
detail -- the same table renders to the same bytes on every host, in every process. The shim
is the only executable file the importer adds; the pack's own runtime package travels next
to it byte-unchanged.

What the rendered shim does, in the sandbox, per run:

* removes every third-party import location (``site-packages`` / ``dist-packages``, the user
  site, anything outside the interpreter's own prefix) from ``sys.path``, the meta-path and
  the module cache BEFORE any pack code is imported -- the sandbox image carries pip,
  setuptools and uv, and an undeclared import of them must fail, not resolve;
* answers ``initialize`` / ``tools/list`` from the embedded table alone (no pack import);
* on ``tools/call`` lazily imports the declared ``module`` and calls the declared ``function``
  with the arguments object, and returns canonical JSON text (and ``structuredContent`` when
  the result is a JSON object). Any failure is a controlled ``isError`` result carrying
  ``Type: message`` -- never a traceback.

``render`` and ``embedded_table`` are the two halves of the parser-level proof the importer
runs: what it rendered is re-read with ``ast`` and compared with the manifest-derived table.
"""

from __future__ import annotations

import ast
import hashlib
import json
from typing import Any

#: Bump on ANY change to ``_TEMPLATE`` or to the table shape. A different generator version
#: yields different bytes, so it must never overwrite an already-registered capability version.
PACK_SHIM_VERSION = "agentnode.pack-shim.v1"

_TABLE_PLACEHOLDER = "__AGENTNODE_TOOL_TABLE__"

_TEMPLATE = '''#!/usr/bin/env python3
"""Generated by agentnode_sdk.capability.pack_import (agentnode.pack-shim.v1). Do not edit.

Serves the tools of ONE imported AgentNode pack over stdio MCP (newline-delimited JSON-RPC).
The tool table below is canonical JSON derived from the pack manifest at import time.
"""
import json
import os
import sys

sys.dont_write_bytecode = True

_HERE = os.path.dirname(os.path.abspath(__file__))
_TABLE_JSON = __AGENTNODE_TOOL_TABLE__
_TOOLS = json.loads(_TABLE_JSON)
_BY_NAME = {t["name"]: t for t in _TOOLS}
PROTOCOL = "2024-11-05"
_STD_FINDER_MODULES = ("_frozen_importlib", "_frozen_importlib_external", "zipimport")


def _third_party(path):
    low = str(path).replace("\\\\", "/").lower()
    return "site-packages" in low or "dist-packages" in low


def _within_interpreter(path):
    if not path:
        return False
    real = os.path.realpath(path)
    for root in {os.path.realpath(sys.base_prefix), os.path.realpath(sys.prefix)}:
        if real == root or real.startswith(root + os.sep):
            return True
    return False


def _origin_module(obj):
    return obj.__module__ if isinstance(obj, type) else type(obj).__module__


def _harden_imports():
    keep = [p for p in sys.path if not _third_party(p) and _within_interpreter(p)
            and os.path.realpath(p) != os.path.realpath(_HERE)]
    sys.path[:] = [_HERE] + keep
    sys.meta_path[:] = [f for f in sys.meta_path if _origin_module(f) in _STD_FINDER_MODULES]
    sys.path_hooks[:] = [h for h in sys.path_hooks if getattr(h, "__module__", "") in _STD_FINDER_MODULES]
    sys.path_importer_cache.clear()
    for name, mod in list(sys.modules.items()):
        where = getattr(mod, "__file__", None)
        if where and _third_party(where):
            del sys.modules[name]
    import importlib
    importlib.invalidate_caches()


def _canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False,
                      allow_nan=False)


def _tool_error(text):
    return {"content": [{"type": "text", "text": text[:2000]}], "isError": True}


def _call(name, arguments):
    tool = _BY_NAME.get(name)
    if tool is None:
        return None
    if not isinstance(arguments, dict):
        return _tool_error("TypeError: tool arguments must be a JSON object")
    try:
        import importlib
        fn = getattr(importlib.import_module(tool["module"]), tool["function"])
        result = fn(**arguments)
    except BaseException as exc:  # noqa: BLE001 -- a controlled tool error, never a traceback
        return _tool_error("%s: %s" % (type(exc).__name__, exc))
    try:
        text = _canonical(result)
    except (TypeError, ValueError) as exc:
        return _tool_error("TypeError: the tool returned a value that is not JSON: %s" % exc)
    out = {"content": [{"type": "text", "text": text}], "isError": False}
    if isinstance(result, dict):
        out["structuredContent"] = json.loads(text)
    return out


def _send(obj):
    sys.stdout.write(json.dumps(obj) + "\\n")
    sys.stdout.flush()


def main():
    _harden_imports()
    for raw in sys.stdin:
        line = raw.strip()
        if not line:
            continue
        try:
            msg = json.loads(line)
        except ValueError:
            continue
        if not isinstance(msg, dict):
            continue
        mid = msg.get("id")
        method = msg.get("method")
        if method == "initialize":
            _send({"jsonrpc": "2.0", "id": mid, "result": {
                "protocolVersion": PROTOCOL,
                "serverInfo": {"name": "agentnode-pack-shim", "version": "1"},
                "capabilities": {"tools": {}}}})
        elif method == "notifications/initialized":
            continue
        elif method == "tools/list":
            _send({"jsonrpc": "2.0", "id": mid, "result": {"tools": [
                {"name": t["name"], "description": t["description"],
                 "inputSchema": t["input_schema"]} for t in _TOOLS]}})
        elif method == "tools/call":
            params = msg.get("params") if isinstance(msg.get("params"), dict) else {}
            result = _call(params.get("name"), params.get("arguments", {}))
            if result is None:
                _send({"jsonrpc": "2.0", "id": mid, "error": {
                    "code": -32602, "message": "unknown tool: %r" % (params.get("name"),)}})
            else:
                _send({"jsonrpc": "2.0", "id": mid, "result": result})
        elif method is not None and mid is not None:
            _send({"jsonrpc": "2.0", "id": mid, "error": {
                "code": -32601, "message": "method not found: %s" % method}})
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''


def canonical_table_json(table: list[dict[str, Any]]) -> str:
    """The ONE serialisation of a tool table: sorted keys, compact, ASCII-only."""
    return json.dumps(table, sort_keys=True, separators=(",", ":"), ensure_ascii=True)


def render(table: list[dict[str, Any]]) -> bytes:
    """Render the shim for *table*. Pure: identical tables give identical bytes."""
    literal = json.dumps(canonical_table_json(table), ensure_ascii=True)
    if _TEMPLATE.count(_TABLE_PLACEHOLDER) != 1:
        raise RuntimeError(
            "pack shim template must carry exactly one table placeholder"
        )
    return _TEMPLATE.replace(_TABLE_PLACEHOLDER, literal).encode("utf-8")


def template_sha256() -> str:
    return hashlib.sha256(_TEMPLATE.encode("utf-8")).hexdigest()


def embedded_table(shim_source: bytes) -> list[dict[str, Any]]:
    """Read the tool table back out of a rendered shim with ``ast`` -- never by executing it."""
    tree = ast.parse(shim_source.decode("utf-8"))
    found = [
        node
        for node in tree.body
        if isinstance(node, ast.Assign)
        and len(node.targets) == 1
        and isinstance(node.targets[0], ast.Name)
        and node.targets[0].id == "_TABLE_JSON"
    ]
    if len(found) != 1:
        raise ValueError("rendered shim must assign _TABLE_JSON exactly once")
    value = ast.literal_eval(found[0].value)
    if not isinstance(value, str):
        raise ValueError("_TABLE_JSON must be a string literal")
    table = json.loads(value)
    if not isinstance(table, list):
        raise ValueError("the embedded tool table must be a list")
    return table
